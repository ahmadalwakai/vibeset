import { randomUUID } from 'node:crypto';
import type { Server } from 'node:http';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

const files = vi.hoisted(() => ({ stat: vi.fn(), readFile: vi.fn() }));
vi.mock('node:fs/promises', () => files);
import { startE2eAssetServer } from '../../scripts/e2e/asset-server';

let server: Server | undefined;
const assetPath = `/themes/${randomUUID()}/v1/${randomUUID()}/thumb.webp`;
const bytes = Buffer.from('fixture');

async function serve(): Promise<string> {
  server = await startE2eAssetServer(randomUUID(), 'http://127.0.0.1:0');
  const address = server.address();
  if (!address || typeof address === 'string') throw new Error('Missing fixture listener');
  return `http://127.0.0.1:${address.port}`;
}

beforeEach(() => {
  vi.resetAllMocks();
  files.stat.mockResolvedValue({ size: bytes.byteLength, isFile: () => true });
  files.readFile.mockResolvedValue(bytes);
});
afterEach(async () => {
  const current = server;
  server = undefined;
  if (current) {
    current.closeAllConnections();
    await new Promise<void>((resolve, reject) =>
      current.close((error) => (error ? reject(error) : resolve())),
    );
  }
});

describe('owned loopback E2E asset transport', () => {
  it('serves generated bytes with an explicit image type and CORS', async () => {
    const origin = await serve();
    const response = await fetch(origin + assetPath);
    expect(response.status).toBe(200);
    expect(Buffer.from(await response.arrayBuffer())).toEqual(bytes);
    expect(response.headers.get('content-type')).toBe('image/webp');
    expect(response.headers.get('access-control-allow-origin')).toBe('*');
    expect(response.headers.get('x-content-type-options')).toBe('nosniff');
  });

  it('supports HEAD without reading file bodies', async () => {
    const origin = await serve();
    const response = await fetch(origin + assetPath, { method: 'HEAD' });
    expect(response.status).toBe(200);
    expect(response.headers.get('content-length')).toBe(String(bytes.byteLength));
    expect(await response.text()).toBe('');
    expect(files.readFile).not.toHaveBeenCalled();
  });

  it('returns a clean404 when a file disappears after stat, and keeps the listener usable', async () => {
    const origin = await serve();
    files.readFile.mockRejectedValueOnce(new Error('fixture read failure'));
    expect((await fetch(origin + assetPath)).status).toBe(404);
    expect((await fetch(origin + assetPath)).status).toBe(200);
  });

  it('rejects changing or oversized file bodies before success headers', async () => {
    const origin = await serve();
    files.readFile.mockResolvedValueOnce(Buffer.from('changed-size'));
    expect((await fetch(origin + assetPath)).status).toBe(404);
    files.stat.mockResolvedValueOnce({ size: 32 * 1024 * 1024 + 1, isFile: () => true });
    expect((await fetch(origin + assetPath)).status).toBe(404);
    expect(files.readFile).toHaveBeenCalledTimes(1);
  });

  it('refuses private paths, encoded traversal, malformed escapes and write methods before file I/O', async () => {
    const origin = await serve();
    for (const name of ['/journal.json', '/%2e%2e%2fjournal.json', '/%E0%A4%A'])
      expect((await fetch(origin + name)).status).toBe(404);
    expect((await fetch(origin + assetPath, { method: 'POST' })).status).toBe(405);
    expect(files.stat).not.toHaveBeenCalled();
    expect(files.readFile).not.toHaveBeenCalled();
  });

  it.each(['https://localhost:3001', 'http://outside.example.com:3001'])(
    'refuses unsupported listeners',
    async (origin) => {
      await expect(startE2eAssetServer(randomUUID(), origin)).rejects.toThrow('Loopback');
    },
  );
});
