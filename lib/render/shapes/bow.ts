import { fmt } from '../svg';

export function bowPath(x: number, y: number, size: number): string {
  const p = (a: number, b: number): string => `${fmt(x + a * size)} ${fmt(y + b * size)}`;
  return `M${p(0.48, 0.43)}C${p(0.24, 0.1)} ${p(0.02, 0.18)} ${p(0.12, 0.47)}C${p(0.18, 0.6)} ${p(0.35, 0.53)} ${p(0.46, 0.49)}L${p(0.28, 0.88)}L${p(0.45, 0.78)}L${p(0.49, 0.98)}L${p(0.55, 0.52)}L${p(0.63, 0.96)}L${p(0.72, 0.78)}L${p(0.91, 0.88)}L${p(0.6, 0.49)}C${p(0.78, 0.57)} ${p(0.99, 0.57)} ${p(0.93, 0.31)}C${p(0.88, 0.11)} ${p(0.67, 0.18)} ${p(0.54, 0.43)}C${p(0.53, 0.38)} ${p(0.48, 0.38)} ${p(0.48, 0.43)}Z`;
}
